// Builds the M2 rollback and re-application SQL from the migration files themselves, so neither can
// drift from what was applied (src/test/m2-rollback-files.test.ts fails if the committed files
// differ from this output):
//   docs/operations/m2-rollback/rollback.sql  undoes 0031, 0032 and the POS part of 0033
//   docs/operations/m2-rollback/reapply.sql   applies 0031, 0032 and 0033 again after that rollback
// Neither is a migration: in a real rollback each becomes the content of a NEW reviewed migration
// (0034, 0035…), applied by the normal runner in its single transaction. They contain no BEGIN or
// COMMIT for that reason (a rehearsal runs them with `psql --single-transaction`).
//
//   node scripts/qa/build-m2-rollback.mjs          # writes both files
//   node scripts/qa/build-m2-rollback.mjs --check  # exit 1 if a committed file differs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const M = (name) =>
  fs.readFileSync(path.join(ROOT, "drizzle/migrations", name), "utf8").replace(/\r\n/g, "\n");

function block(src, start, end, label) {
  const i = src.indexOf(start);
  if (i < 0 || src.indexOf(start, i + 1) >= 0)
    throw new Error(`${label}: expected exactly one "${start}"`);
  const j = src.indexOf(end, i);
  if (j < 0) throw new Error(`${label}: end not found`);
  return src.slice(i, j + end.length);
}
function replaceOnce(src, from, to, label) {
  if (src.split(from).length !== 2) throw new Error(`${label}: expected exactly one "${from}"`);
  return src.replace(from, to);
}

export function buildM2RollbackFiles() {
  const m0018 = M("0018_member_permissions.sql");
  const m0019 = M("0019_permission_performance.sql");
  const m0020 = M("0020_inventory_cost_permission.sql");
  const m0025 = M("0025_store_sales_tax_rate.sql");
  const m0031 = M("0031_ledger_day_totals.sql");
  const m0032 = M("0032_pos_pending_sale_resolution.sql");
  const m0033 = M("0033_member_grant_integrity_and_pending_hardening.sql");

  const sale0025 = block(
    m0025,
    "CREATE OR REPLACE FUNCTION public.create_pos_sale_v2(",
    "$function$;",
    "0025 sale",
  );
  const catalog0020 = block(
    m0020,
    "create or replace function public.permission_catalog()",
    "$$;",
    "0020 catalog",
  );
  const ceiling0018 = block(
    m0018,
    "create or replace function public.role_ceiling(",
    "$$;",
    "0018 ceiling",
  );
  const defaults0018 = block(
    m0018,
    "create or replace function public.role_default_permissions(",
    "$$;",
    "0018 defaults",
  );
  const policy0019 = block(
    m0019,
    "alter policy finance_read on public.finance_entries using (",
    ")));",
    "0019 policy",
  );

  const rollback = `-- M2 ROLLBACK — undoes 0031 (ledger aggregation), 0032 (pending-sale resolution) and the POS part of
-- 0033. GENERATED by scripts/qa/build-m2-rollback.mjs from the migration files; do not edit by hand.
-- Not a migration: in a real rollback this becomes a NEW reviewed migration, applied by the normal
-- runner (one transaction). Order: 0033 POS part and 0032 first, then 0031. Never DROP ... CASCADE
-- (it would also drop the finance_read policy, which depends on accessible_location_ids).
--
-- Kept on purpose:
--   * pos_sale_key_voids (closed keys + history): requests still travelling must stay refused if
--     the feature comes back, and the rows are part of the audit trail;
--   * revoked_permissions entries of orders.resolve_pending: a revocation only ever narrows access;
--     dropping it could re-grant the permission (e.g. to an organization admin) on a later reapply;
--   * the member-grant integrity of 0033 (part A: tier ceiling, manager's own permissions, trigger):
--     a security fix independent of M2.
-- Removed so that a later reapply cannot reactivate anything silently: orders.resolve_pending in
-- EVERY permission profile (system AND custom) and in every member's individual grants.
set local lock_timeout = '5s';

-- ---------------------------------------------------------------- 0033 (POS part) + 0032
-- create_pos_sale_v2 back to the 0025 body (same signature: owner and ACL are kept)
${sale0025}
-- the resolution RPC goes away (pos_sale_key_voids is kept)
drop function if exists public.resolve_pending_pos_sale(uuid, uuid, text, text, integer, integer, timestamptz);
-- catalog (0020), tier ceiling and defaults (0018)
${catalog0020}
${ceiling0018}
${defaults0018}
-- the permission leaves every profile, system and custom (the profile trigger refreshes its members)
update public.permission_profiles
   set permissions = array_remove(permissions, 'orders.resolve_pending'), updated_at = now()
 where 'orders.resolve_pending' = any(permissions);
-- …and every individual grant (revocations are kept, see above)
update public.organization_members
   set extra_permissions = array_remove(extra_permissions, 'orders.resolve_pending')
 where 'orders.resolve_pending' = any(extra_permissions);
update public.organization_members
   set effective_permissions = public.effective_permissions_for(role, profile_id, extra_permissions, revoked_permissions);

-- ---------------------------------------------------------------- 0031
-- finance_read back to the 0019 expression
${policy0019}
drop function if exists public.ledger_day_totals(uuid, uuid[], integer, boolean);
drop function if exists public.accessible_location_ids();
`;

  let again0032 = replaceOnce(
    m0032,
    "create table public.pos_sale_key_voids (",
    "create table if not exists public.pos_sale_key_voids (",
    "0032 table",
  );
  again0032 = replaceOnce(
    again0032,
    "create policy pos_voids_read on public.pos_sale_key_voids",
    "drop policy if exists pos_voids_read on public.pos_sale_key_voids;\ncreate policy pos_voids_read on public.pos_sale_key_voids",
    "0032 policy",
  );

  const reapply = `-- M2 RE-APPLICATION after docs/operations/m2-rollback/rollback.sql — 0031, 0032 and 0033 again, made
-- idempotent where the rollback kept an object (pos_sale_key_voids and its policy). GENERATED by
-- scripts/qa/build-m2-rollback.mjs from the migration files; do not edit by hand. Not a migration:
-- it becomes a NEW reviewed migration. It grants orders.resolve_pending to the system org_admin
-- profile only (as 0032 did); custom profiles and individual grants were stripped by the rollback
-- and stay without it until an owner grants it again; revocations kept by the rollback still apply.
-- ===================================================================== 0031
${m0031}
-- ===================================================================== 0032
${again0032}
-- ===================================================================== 0033
${m0033}`;
  return { rollback, reapply };
}

const OUT = path.join(ROOT, "docs/operations/m2-rollback");
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const files = buildM2RollbackFiles();
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [name, content] of Object.entries(files)) {
    const file = path.join(OUT, `${name}.sql`);
    if (check) {
      const current = fs.existsSync(file)
        ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n")
        : "";
      if (current !== content) (stale++, console.log(`STALE ${path.relative(ROOT, file)}`));
    } else {
      fs.mkdirSync(OUT, { recursive: true });
      fs.writeFileSync(file, content);
      console.log(`wrote ${path.relative(ROOT, file)}`);
    }
  }
  if (stale) process.exit(1);
}
