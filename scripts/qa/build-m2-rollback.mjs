// Builds the M2 rollback and re-application SQL from the migration files themselves, so neither can
// drift from what was applied (src/test/m2-rollback-files.test.ts fails if the committed files
// differ from this output):
//   docs/operations/m2-rollback/rollback.sql  undoes 0031 and 0032 (keeps the closed keys and 0033)
//   docs/operations/m2-rollback/reapply.sql   applies 0031, 0032, 0033 and 0035 again after that rollback
//   docs/operations/security-closure/0034-rollback.sql  undoes 0034 (admin_assign_owner back to 0001)
//   docs/operations/security-closure/0035-rollback.sql  undoes the functions and policy of 0035
//   docs/operations/security-closure/0036-rollback.sql  undoes 0036 (legacy sale RPCs callable again)
// (0034, 0035 and 0036 are re-applied by running the migration file again: every statement is idempotent.)
// Neither is a migration: in a real rollback each becomes the content of a NEW reviewed migration
// (0034, 0035…), applied by the normal runner in its single transaction. They contain no BEGIN or
// COMMIT for that reason (a rehearsal runs them with `psql --single-transaction`).
//
//   node scripts/qa/build-m2-rollback.mjs          # writes both files
//   node scripts/qa/build-m2-rollback.mjs --check  # exit 1 if a committed file differs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const M = (name) =>
  fs.readFileSync(path.join(ROOT, "drizzle/migrations", name), "utf8").replace(/\r\n/g, "\n");

function block(src, start, end, label) {
  const i = src.indexOf(start);
  if (i < 0 || src.indexOf(start, i + 1) >= 0)
    throw new Error(`${label}: expected exactly one "${start}"`);
  const j = src.indexOf(end, i);
  if (j < 0) throw new Error(`${label}: end not found`);
  return src.slice(i, j + end.length);
}
function replaceOnce(src, from, to, label) {
  if (src.split(from).length !== 2) throw new Error(`${label}: expected exactly one "${from}"`);
  return src.replace(from, () => to);
}

export function buildM2RollbackFiles() {
  const m0018 = M("0018_member_permissions.sql");
  const m0019 = M("0019_permission_performance.sql");
  const m0020 = M("0020_inventory_cost_permission.sql");
  const m0031 = M("0031_ledger_day_totals.sql");
  const m0032 = M("0032_pos_pending_sale_resolution.sql");
  const m0033 = M("0033_member_grant_integrity_and_pending_hardening.sql");
  const m0035 = M("0035_pending_sale_reason_privacy.sql");

  const catalog0020 = block(
    m0020,
    "create or replace function public.permission_catalog()",
    "$$;",
    "0020 catalog",
  );
  const ceiling0018 = block(
    m0018,
    "create or replace function public.role_ceiling(",
    "$$;",
    "0018 ceiling",
  );
  const defaults0018 = block(
    m0018,
    "create or replace function public.role_default_permissions(",
    "$$;",
    "0018 defaults",
  );
  const policy0019 = block(
    m0019,
    "alter policy finance_read on public.finance_entries using (",
    ")));",
    "0019 policy",
  );

  const rollback = `-- M2 ROLLBACK - undoes 0031 (ledger aggregation) and 0032 (manual resolution of pending sales).
-- GENERATED by scripts/qa/build-m2-rollback.mjs from the migration files; do not edit by hand.
-- Not a migration: in a real rollback this becomes a NEW reviewed migration, applied by the normal
-- runner (one transaction). Order: 0032 first, then 0031. Never DROP ... CASCADE (it would also drop
-- the finance_read policy, which depends on accessible_location_ids).
--
-- Kept on purpose:
--   * create_pos_sale_v2 as 0033 left it (closed-key check + READ COMMITTED check) and the closed keys
--     (pos_sale_key_voids): a key someone closed must stay closed while the feature is rolled back -
--     the register that held that pending sale may resend it at any time, and the sale was settled
--     by other means; restoring the 0025 body would record it twice;
--   * revoked_permissions entries of orders.resolve_pending (set_member_access keeps revocations of
--     permissions outside the catalog): a revocation only narrows access; losing it would re-grant
--     the permission to an organization admin on a later re-application;
--   * the member-grant integrity of 0033 (part A): a security fix independent of M2.
-- Removed, so that a later re-application cannot reactivate anything silently, and audited:
-- orders.resolve_pending in EVERY permission profile (system AND custom) and every individual grant.
set local lock_timeout = '5s';

-- ---------------------------------------------------------------- 0032
-- the resolution RPC goes away (create_pos_sale_v2 and pos_sale_key_voids are kept, see above)
drop function if exists public.resolve_pending_pos_sale(uuid, uuid, text, text, integer, integer, timestamptz);
-- ...and the reader of the justifications (0035); their private store and its rows are kept
drop function if exists public.list_pending_sale_reasons(uuid, uuid, text, integer);
-- catalog (0020), tier ceiling and defaults (0018)
${catalog0020}
${ceiling0018}
${defaults0018}
-- the permission leaves every profile, system and custom (custom ones audited; the profile trigger
-- refreshes their members)
do $$
declare p record;
begin
  for p in select id, org_id, name from public.permission_profiles
            where 'orders.resolve_pending' = any(permissions) and org_id is not null loop
    perform public.write_audit(p.org_id, 'permission_profile.saved', p.id::text, jsonb_build_object(
      'name', p.name, 'removed', to_jsonb(array['orders.resolve_pending']), 'reason', 'm2_rollback'));
  end loop;
end $$;
update public.permission_profiles
   set permissions = array_remove(permissions, 'orders.resolve_pending'), updated_at = now()
 where 'orders.resolve_pending' = any(permissions);
-- ...and every individual grant: the 0033 trigger drops what the (restored) tier cannot hold and audits
-- it (member.extras_pruned); revocations are kept
update public.organization_members
   set extra_permissions = extra_permissions
 where 'orders.resolve_pending' = any(extra_permissions);
update public.organization_members
   set effective_permissions = public.effective_permissions_for(role, profile_id, extra_permissions, revoked_permissions);

-- ---------------------------------------------------------------- 0031
-- finance_read back to the 0019 expression
${policy0019}
drop function if exists public.ledger_day_totals(uuid, uuid[], integer, boolean);
drop function if exists public.accessible_location_ids();
`;

  let again0032 = replaceOnce(
    m0032,
    "create table public.pos_sale_key_voids (",
    "create table if not exists public.pos_sale_key_voids (",
    "0032 table",
  );
  again0032 = replaceOnce(
    again0032,
    "create policy pos_voids_read on public.pos_sale_key_voids",
    "drop policy if exists pos_voids_read on public.pos_sale_key_voids;\ncreate policy pos_voids_read on public.pos_sale_key_voids",
    "0032 policy",
  );

  const reapply = `-- M2 RE-APPLICATION after docs/operations/m2-rollback/rollback.sql - 0031, 0032, 0033 and 0035 again, made
-- idempotent where the rollback kept an object (pos_sale_key_voids and its policy). GENERATED by
-- scripts/qa/build-m2-rollback.mjs from the migration files; do not edit by hand. Not a migration:
-- it becomes a NEW reviewed migration. It grants orders.resolve_pending to the system org_admin
-- profile only (as 0032 did); custom profiles and individual grants were stripped by the rollback
-- and stay without it until an owner grants it again; revocations kept by the rollback still apply.
-- ===================================================================== 0031
${m0031}
-- ===================================================================== 0032
${again0032}
-- ===================================================================== 0033
${m0033}
-- ===================================================================== 0035
-- (after 0033: the 0033 resolution body would store the justification in the closed key and the audit)
${m0035}`;
  return { rollback, reapply };
}

/**
 * Rollback of the security closure migrations (0034, 0035, 0036). Each is a NEW reviewed migration when
 * used; re-application is the migration file itself (idempotent). Generated from the files, so the
 * restored bodies are exactly the previous ones.
 */
export function buildSecurityClosureRollbackFiles() {
  const m0001 = M("0001_tenant_hardening_audit_control_center.sql");
  const m0019 = M("0019_permission_performance.sql");
  const m0033 = M("0033_member_grant_integrity_and_pending_hardening.sql");
  const assign0001 = block(
    m0001,
    "create or replace function public.admin_assign_owner(",
    "end $$;",
    "0001 admin_assign_owner",
  );
  const resolve0033 = block(
    m0033,
    "create or replace function public.resolve_pending_pos_sale(",
    "end $$;",
    "0033 resolve_pending_pos_sale",
  );
  const audit0019 = block(
    m0019,
    'alter policy "Org managers read org audit" on public.audit_logs using (',
    "])));",
    "0019 audit policy",
  );
  const resolveSig =
    "public.resolve_pending_pos_sale(uuid, uuid, text, text, integer, integer, timestamptz)";
  if (resolve0033.includes("$rb$"))
    throw new Error("0033 resolve_pending_pos_sale: unexpected $rb$ quote");
  const role0001 = block(
    m0001,
    "create or replace function public.admin_set_platform_role(",
    "end $$;",
    "0001 admin_set_platform_role",
  );
  const rollback0034 = `-- 0034 ROLLBACK - admin_assign_owner and admin_set_platform_role back to their 0001 bodies; the three
-- 0034 trigger functions become no-ops.
-- GENERATED by scripts/qa/build-m2-rollback.mjs from the migration files; do not edit by hand.
-- Not a migration: in a real rollback this becomes a NEW reviewed migration (one transaction).
-- WARNING: this restores the escalation 0034 closed: a platform admin can again become the owner of
-- any organization, its own account included, and demote or remove its owners; a platform role can
-- again be granted to an owner of a customer organization, and an account with a platform role can
-- again become owner of one; an e-mail matching two accounts again picks one of them.
-- The triggers stay (DROP TRIGGER would take an ACCESS EXCLUSIVE lock on organization_members, read
-- by every permission check); their functions do nothing. Re-application: run 0034 again (idempotent).
set local lock_timeout = '5s';
${assign0001}
${role0001}
create or replace function public.trg_owner_platform_separation()
returns trigger language plpgsql set search_path = public as $$
begin
  return null; -- 0034 rolled back: no owner-side separation
end $$;
create or replace function public.trg_member_owner_serialize()
returns trigger language plpgsql set search_path = public as $$
begin
  return new; -- 0034 rolled back: no per-organization lock
end $$;
create or replace function public.trg_platform_role_separation()
returns trigger language plpgsql set search_path = public as $$
begin
  return new; -- 0034 rolled back: no operator/owner separation
end $$;
`;
  const rollback0035 = `-- 0035 ROLLBACK - the resolution RPC back to its 0033 body (only if it exists), the activity log back
-- to the 0019 policy, the justification reader and the audit helper removed. GENERATED by
-- scripts/qa/build-m2-rollback.mjs from the migration files; do not edit by hand. Not a migration: it
-- becomes a NEW reviewed migration (one transaction).
-- WARNING: until 0035 is applied again this WIDENS ACCESS for new events:
--   * every NEW resolution stores its justification as 0033 did: in the closed key (column not
--     selectable through the API, kept below) AND in the audit metadata, readable by every
--     team.activity holder of the organization (managers of other stores included) and by every
--     platform admin;
--   * the activity log loses its store scope for ALL events (0019 policy).
-- Not widened: the texts already moved stay in pos_pending_resolution_reasons and are NOT put back;
-- the closed keys keep the column-level read privilege of 0035.
-- If the M2 rollback (docs/operations/m2-rollback/rollback.sql) already dropped
-- resolve_pending_pos_sale, it is NOT recreated here (owners would otherwise regain it).
-- Re-application: run 0035 again (idempotent; it moves the texts written meanwhile).
set local lock_timeout = '5s';
do $rb$
begin
  if to_regprocedure('${resolveSig}') is not null then
    execute $fn$${resolve0033.replace(/;$/, "")}
$fn$;
  end if;
end $rb$;
drop function if exists public.list_pending_sale_reasons(uuid, uuid, text, integer);
${audit0019}
drop function if exists public.audit_visible_location_ids();
`;
  // 0036: the exact signatures the migration revokes (read from the file, so they cannot drift)
  const m0036 = M("0036_retire_legacy_pos_sale_rpcs.sql");
  const retired = [
    ...m0036.matchAll(
      /^revoke all on function (public\.[a-z_]+\([^)]*\))\n {2}from public, anon, authenticated, service_role;$/gm,
    ),
  ].map((m) => m[1]);
  if (retired.length !== 3)
    throw new Error(`0036: expected 3 revoked functions, found ${retired.length}`);
  const rollback0036 = `-- 0036 ROLLBACK - the three basis-point sale RPCs callable by signed-in users again (as before 0036).
-- GENERATED by scripts/qa/build-m2-rollback.mjs from the migration file; do not edit by hand.
-- Not a migration: in a real rollback this becomes a NEW reviewed migration (one transaction).
-- Only needed if a deployed server build older than 10b2d94 (before 0025) must record sales again.
-- It reopens three redundant entry points; it does NOT reopen a way around closed keys (the wrappers
-- delegate to v2). anon and service_role get nothing back. Re-application: run 0036 again (idempotent).
set local lock_timeout = '5s';
${retired.map((f) => `grant execute on function ${f} to authenticated;\ncomment on function ${f} is null;`).join("\n")}
`;
  return {
    "0034-rollback": rollback0034,
    "0035-rollback": rollback0035,
    "0036-rollback": rollback0036,
  };
}

const OUTPUTS = [
  [path.join(ROOT, "docs/operations/m2-rollback"), buildM2RollbackFiles],
  [path.join(ROOT, "docs/operations/security-closure"), buildSecurityClosureRollbackFiles],
];
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [out, build] of OUTPUTS)
    for (const [name, content] of Object.entries(build())) {
      const file = path.join(out, `${name}.sql`);
      if (check) {
        const current = fs.existsSync(file)
          ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n")
          : "";
        if (current !== content) (stale++, console.log(`STALE ${path.relative(ROOT, file)}`));
      } else {
        fs.mkdirSync(out, { recursive: true });
        fs.writeFileSync(file, content);
        console.log(`wrote ${path.relative(ROOT, file)}`);
      }
    }
  if (stale) process.exit(1);
}
